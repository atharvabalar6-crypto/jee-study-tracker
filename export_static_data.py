"""
export_static_data.py - Exports all JEE Study Tracker data into static JSON
and a standalone JS bundle so the site can run 100% serverlessly on GitHub Pages.
"""
import os
import json
import sqlite3

def export_all():
    base_dir = os.path.dirname(os.path.abspath(__file__))
    
    # 1. Load syllabus
    from seed_data import SYLLABUS, QUESTIONS
    from formula_bank import get_all_formulas
    from chapter_notes import generate_notes_for_chapter
    
    print(f"Exporting {len(SYLLABUS)} chapters...")
    chapters_export = []
    for c in SYLLABUS:
        chapters_export.append({
            "subject": c["subject"],
            "name": c["chapter"],
            "class_level": c["class_level"],
            "ncert_order": c["ncert_order"],
            "importance": c["importance"],
            "topics": c["topics"],
            "tests_given": 0,
            "last_score_pct": 0,
            "mastery_status": "Untested"
        })

    # 2. Load all formulas
    all_formulas = get_all_formulas()
    print(f"Exporting {len(all_formulas)} formulas...")

    # 3. Load all questions
    print(f"Exporting {len(QUESTIONS)} questions...")

    # 4. Generate all notes
    print("Pre-rendering all 96 chapter notes...")
    notes_export = {}
    for c in SYLLABUS:
        chap_name = c["chapter"]
        notes_export[chap_name] = generate_notes_for_chapter(chap_name)

    data_bundle = {
        "chapters": chapters_export,
        "formulas": all_formulas,
        "questions": QUESTIONS,
        "notes": notes_export
    }

    # Write as JSON
    os.makedirs(os.path.join(base_dir, "static", "data"), exist_ok=True)
    json_path = os.path.join(base_dir, "static", "data", "jee_data.json")
    with open(json_path, "w", encoding="utf-8") as f:
        json.dump(data_bundle, f, ensure_ascii=False)
    print(f"Wrote JSON to {json_path} ({os.path.getsize(json_path) / 1024:.1f} KB)")

    # Write as standalone JS bundle window.JEE_STATIC_DATA
    js_path = os.path.join(base_dir, "static", "js", "jee_static_data.js")
    with open(js_path, "w", encoding="utf-8") as f:
        f.write("// Autogenerated static dataset for GitHub Pages serverless deployment\n")
        f.write("window.JEE_STATIC_DATA = ")
        json.dump(data_bundle, f, ensure_ascii=False)
        f.write(";\n")
    print(f"Wrote JS bundle to {js_path} ({os.path.getsize(js_path) / 1024:.1f} KB)")

if __name__ == "__main__":
    export_all()
